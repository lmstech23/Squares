-- Roster identity -- email primary, phone secondary.
--
-- identity_key is RENAMED, not duplicated. Same meaning, same values: it has
-- always held a trimmed, lowercased email. The name became ambiguous the
-- moment a second key existed, and a rename carries the data and the index
-- with it -- no backfill, no dual-write window, no legacy-key deprecation
-- step. The index is renamed alongside so nothing is left saying identity_key.
--
-- phone_key is the only genuinely new column.
--
-- UNIQUE ON BOTH. One normalized email and one normalized phone per supporter
-- within an event. Ordered lookup -- email, then phone, never OR -- then binds
-- to AT MOST ONE existing supporter, with no set to order and therefore no
-- tie-break anywhere. `email OR phone` would chain transitively: A shares an
-- email with B, B shares a phone with C, C is silently merged into A.
--
-- NULLS DO NOT BLOCK THE UNIQUE INDEX. Postgres treats them as distinct, so
-- the one legacy supporter with no phone is fine and could never collide.
-- Presence is enforced by the application, uniqueness by the index.
--
-- THE BACKFILL IS GENERATED, not hand-written:
--   node --experimental-strip-types scripts/generate-phone-backfill.mts
-- It imports the same normalizePhone the write path calls. Reimplementing
-- E.164 in PL/pgSQL would be exactly the second implementation the rule
-- forbids, and the one that drifts. Verify afterwards with --verify, which
-- re-runs the real function over the stored values and asserts a no-op.

ALTER TABLE "event_supporters" RENAME COLUMN "identity_key" TO "email_key";
ALTER INDEX "event_supporters_event_identity_key" RENAME TO "event_supporters_event_email_key";

ALTER TABLE "event_supporters" ADD COLUMN "phone_key" TEXT;

