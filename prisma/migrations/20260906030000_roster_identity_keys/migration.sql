CREATE UNIQUE INDEX "event_supporters_event_phone_key"
  ON "event_supporters" ("event_id", "phone_key");

-- GATE. Same transaction, so a failure rolls the whole thing back rather than
-- leaving a half-keyed table.
DO $$
DECLARE
  bad_shape INTEGER;
  dupes     INTEGER;
BEGIN
  -- Shape only. The authoritative no-op check runs through the real
  -- normalizer in --verify; this catches a mangled generator output.
  SELECT count(*) INTO bad_shape
    FROM event_supporters
   WHERE phone_key IS NOT NULL
     AND phone_key !~ '^\+[0-9]{8,15}$';
  IF bad_shape > 0 THEN
    RAISE EXCEPTION 'roster identity aborted: % phone_key value(s) are not E.164', bad_shape;
  END IF;

  SELECT count(*) INTO dupes FROM (
    SELECT event_id, phone_key FROM event_supporters
     WHERE phone_key IS NOT NULL
     GROUP BY event_id, phone_key HAVING count(*) > 1) d;
  IF dupes > 0 THEN
    RAISE EXCEPTION
      'roster identity aborted: % duplicate (event_id, phone_key) group(s); resolve the supporters first',
      dupes;
  END IF;
END $$;
